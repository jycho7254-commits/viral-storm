HDR_FILL = PatternFill("solid", fgColor="1F4E79")
HDR_FONT = Font(bold=True, color="FFFFFF", size=11)
C1_FILL = PatternFill("solid", fgColor="E2EFDA")   # 润色-绿
C2_FILL = PatternFill("solid", fgColor="FCE4EC")   # 写错-红
C3_FILL = PatternFill("solid", fgColor="FFF2CC")   # 其他-黄
C0_FILL = PatternFill("solid", fgColor="F2F2F2")   # 通过-灰
THIN = Border(*[Side(style="thin", color="BFBFBF")] * 4)

def style_header(ws, cols):
    for c in range(1, cols + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill = HDR_FILL
        cell.font = HDR_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = THIN

def cat_fill(cat):
    return {1: C1_FILL, 2: C2_FILL, 3: C3_FILL, 0: C0_FILL}.get(cat)

